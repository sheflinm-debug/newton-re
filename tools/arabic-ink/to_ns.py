#!/usr/bin/env python3
"""Turn Arabic ink samples into a NewtonScript script that replays them
through the reconstruction's cursive recogniser.

Purpose:  see what ParaGraph's cursive reader makes of real Arabic
          handwriting, as written and mirrored left to right, without a pen
          on the host: each sample is handed to Recognize() as a stroke
          bundle and the readings are printed.  Run with
          NEWTON_TRACE_CURSIVE=1 to see each stage (the low level's xrs,
          the word graph, the answers).
Inputs:   the samples directory serve.py writes (default
          build/arabic-ink/samples/): one JSON file per sample, strokes as
          flat [x, y, t, pressure, ...] arrays in CSS pixels, with the
          slate's guide lines (slate.topLine, slate.baseLine).
Outputs:  a NewtonScript file (default build/arabic-ink/replay.ns, or
          replay-mirrored.ns with --mirror) and, beside it, an index
          <out>.tsv of sample number, file id and word (the script prints
          only numbers and ids: the host's console may not show Arabic).
          Before each sample the script calls HostXrDumpMark(id), so a run
          with NEWTON_XR_DUMP=<file> (recognition/XrDump.h) records which
          sample each word's xrs came from (xrs.py reads the record).
Usage:    python tools/arabic-ink/to_ns.py [--samples DIR] [-o FILE]
              [--mirror] [--band PIXELS] [--word W]... [--start N --count N]
          build/host/host/newton --rom build/MP2x00US/rom.bin
              --display 320x480 --script build/arabic-ink/replay.ns
              --headless 300
          The script prints "arabic: <n> <id> info <i>: reading | reading"
          for each sample and "arabic: done" at the end.

Geometry.  The sample is scaled so that the band between the slate's two
guide lines is --band screen pixels tall (default 16, about the Newton's
own cursive demo's x-height) - or smaller, so that the word is no wider
than --max-width pixels (default 260: it must fit the 320-pixel screen, as
a long word written on a MessagePad is written smaller; at 16 alone half of
ADAB's place names ran off the screen, and the widest past the word
segmenter's line, which overran its histogram) - its base line put on
y = 200 and its left edge at x = 40, and the points are handed in eighths of a pixel (stroke
format 2, the tablet's own resolution) so nothing is lost to rounding.
--mirror flips each sample left to right (x -> right edge - x) before
that, so that Arabic, written right to left, reaches the recogniser as
writing that runs left to right.  Points that round to the same place as
the one before are dropped.
"""

import argparse
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arabic   # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

BASE_Y = 200        # the base line on the Newton's screen
LEFT_X = 40         # the sample's left edge there


def load(samples_dir, words):
    out = []
    for path in sorted(glob.glob(os.path.join(samples_dir, "*.json"))):
        with open(path, encoding="utf-8") as f:
            d = json.load(f)
        if words and d.get("word") not in words:
            continue
        if d.get("strokes"):
            out.append((os.path.basename(path)[:-5], d))
    return out


def convert(d, band, mirror, max_width):
    """The sample's strokes as Newton stroke arrays: v, h, v, h, ... in
    eighths of a pixel."""
    slate = d["slate"]
    xs = [s[i] for s in d["strokes"] for i in range(0, len(s), 4)]
    lo, hi = min(xs), max(xs)
    scale = band / float(slate["baseLine"] - slate["topLine"])
    if hi > lo:
        scale = min(scale, max_width / float(hi - lo))
    strokes = []
    for s in d["strokes"]:
        pts = []
        for i in range(0, len(s), 4):
            x, y = s[i], s[i + 1]
            x = (hi - x) if mirror else (x - lo)
            h = round((LEFT_X + x * scale) * 8)
            v = round((BASE_Y + (y - slate["baseLine"]) * scale) * 8)
            if len(pts) >= 2 and pts[-2] == v and pts[-1] == h:
                continue
            pts += [v, h]
        strokes.append(pts)
    return strokes


def dictionary_words(path):
    """The vocabulary's words as codes: each space-separated word of each
    sample's label in a samples directory, or each line of a text file."""
    words = set()
    if os.path.isdir(path):
        for f in glob.glob(os.path.join(path, "**", "*.json"), recursive=True):
            with open(f, encoding="utf-8") as h:
                words.update(arabic.encode(json.load(h).get("word", "")).split())
    else:
        with open(path, encoding="utf-8") as h:
            for line in h:
                words.update(arabic.encode(line.strip()).split())
    return sorted(w for w in words if w)


SCRIPT_HEAD = """// Generated by tools/arabic-ink/to_ns.py - regenerate, don't edit.
// Arabic ink samples%(mirrored)s read by the cursive recogniser.
HostInclude("%(common)s");

name := [2, 0, 45, 34, 14, 37];		// "Daniel" in ADB key codes, as the demos' owner

arabicSamples := [
%(samples)s
];

%(dictionary)s
arabicReadings := func(ci)
  begin
    local out := [];
    if ci and ci.info then
      foreach i, info in ci.info do
        begin
          local words := [];
          if info.words then
            foreach w in info.words do AddArraySlot(words, w.word);
          AddArraySlot(out, words);
        end;
    out;
  end;

call walkSetup with (name, func() begin
    SetUserConfig('letterSetSelection, 0);		// cursive: ParaGraph's reader
    ReadCursiveOptions();
    Print("arabic: letter set" && GetUserConfig('letterSetSelection) && "-" && Length(arabicSamples) && "samples");
    foreach n, s in arabicSamples do
      begin
        Print("arabic: sample" && n && s.id);
        HostXrDumpMark(s.id);
        local ci := Recognize([MakeStrokeBundle(s.strokes, 2)], arabicConfig, nil);
        local readings := call arabicReadings with (ci);
        if Length(readings) = 0 then
          Print("arabic:" && n && s.id && "nothing")
        else
          foreach i, words in readings do
            begin
              local line := "arabic:" && n && s.id && "info" && i & ":";
              foreach k, w in words do line := line && (if k > 0 then "| " else "") & w;
              Print(line);
            end;
      end;
    Print("arabic: done");
    HostQuit();
  end);
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--samples", default=os.path.join(REPO, "build", "arabic-ink", "samples"))
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--mirror", action="store_true", help="flip each sample left to right")
    ap.add_argument("--band", type=float, default=16.0, help="screen pixels between the guide lines")
    ap.add_argument("--max-width", type=float, default=260.0, help="the widest a word may be on the screen (pixels)")
    ap.add_argument("--word", action="append", default=[], help="only samples of this word (repeatable)")
    ap.add_argument("--start", type=int, default=0, help="skip this many samples (in file order)")
    ap.add_argument("--count", type=int, default=0, help="at most this many samples (0: all)")
    ap.add_argument("--dictionary", help="a samples directory, or a text file of words, as the reader's vocabulary")
    args = ap.parse_args()

    out = args.out or os.path.join(REPO, "build", "arabic-ink", "replay-mirrored.ns" if args.mirror else "replay.ns")
    samples = load(args.samples, set(args.word))[args.start:]
    if args.count:
        samples = samples[:args.count]
    if not samples:
        print("no samples in %s" % args.samples, file=sys.stderr)
        return 1

    dictionary = "arabicConfig := nil;"
    if args.dictionary:
        words = dictionary_words(args.dictionary)
        literal = ", ".join('"' + w.replace("\\", "\\\\").replace('"', '\\"') + '"' for w in words)
        dictionary = ("// the vocabulary: %d words of %s, as arabic.py's codes\n"
                      "arabicDict := NewDictionary(true);\n"
                      "foreach w in [%s] do AddWordToDictionary(arabicDict, w);\n"
                      "arabicConfig := {_proto: HostRerecognizeConfig(), dictionaries: [arabicDict]};" % (len(words), args.dictionary.replace("\\", "/"), literal))
    common = os.path.relpath(os.path.join(REPO, "src", "host", "demo", "common.ns"), os.path.dirname(os.path.abspath(out)))
    lines = []
    for sid, d in samples:
        strokes = convert(d, args.band, args.mirror, args.max_width)
        body = ",\n      ".join("[" + ", ".join(str(n) for n in s) + "]" for s in strokes)
        lines.append("  {id: \"%s\", strokes: [\n      %s]}" % (sid, body))
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(SCRIPT_HEAD % {"mirrored": " (mirrored)" if args.mirror else "", "dictionary": dictionary,
                               "common": common.replace("\\", "/"),
                               "samples": ",\n".join(lines)})
    with open(os.path.splitext(out)[0] + ".tsv", "w", encoding="utf-8", newline="\n") as f:
        for n, (sid, d) in enumerate(samples):
            f.write("%d\t%s\t%s\n" % (n, sid, d["word"]))
    print("wrote %s: %d samples" % (out, len(samples)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
