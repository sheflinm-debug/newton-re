#!/usr/bin/env python3
"""Audit the Arabic engine on the Newton: known handwriting written with the
pen onto the Notepad, the page read back, and every loss put where it
happens.

Purpose:  the offline numbers (eval_net.py) say what the network makes of a
          sample; what the user sees is what comes out of the whole path -
          the tablet's points in screen pixels, the engine's grouping of
          strokes into words (ArabicRecognizer::Group), the network in C++,
          the confidence that decides word or ink, and the paragraph.  Each
          case is read three ways:
            offline  the network (onnxruntime) on the sample's own points
            screen   the network on the very points handed to the Newton
            newton   what the Notepad's paragraph says after the pen wrote it
          so that offline -> screen is what the screen's size and pixel
          grid cost, screen -> newton what the Newton side costs (grouping,
          ink, the C++ features), and offline alone the network.
Inputs:   samples directories (serve.py's, adab.py's), a model (.onnx, its
          .json beside it - the one the engine's .anet was exported from)
          and the newton program.
Cases:    --words DIR   each sample alone, its word the expected text
          --phrases DIR pairs of that directory's samples written side by
                        side, right to left, a word gap apart: "w1 w2"
          --limit N     at most N samples of each directory (spread evenly)
Outputs:  <out>/audit.ns (the script), <out>/audit.log (newton's output),
          <out>/audit.tsv (one line per case: kind, id, expected, the three
          readings, strokes written, units the engine read, confidence),
          and a summary on stdout and in <out>/audit.txt: letters wrong and
          words right for each reading, the cases where the Newton read
          differently from the screen points (and why: the word split into
          several units, read as ink, or the features), and the letters
          most often confused.
Usage:    build/venv/Scripts/python tools/arabic-ink/audit.py
              --model build/arabic-ink/arabic-net-tuned.onnx
              --words build/arabic-ink/samples --words build/arabic-ink/adab/set_3 --limit 60
              --phrases build/arabic-ink/samples --phrase-count 20
              [--band 30] [--gap 0.6] [--newton build/host/host/newton.exe]
              [--out build/arabic-ink/audit] [--no-run]
          The newton run is headless (about two seconds a case); the
          engine's network is the one newton finds (NEWTON_ARABIC_NET, else
          arabic-net.anet beside it): give --anet to name it.

Geometry: a sample is scaled so the band between the capture slate's guide
lines is --band screen pixels (no wider than 270), its right edge at
x = 295 and its base line on y = 200, rounded to whole pixels as the
tablet gives them; a phrase's second word is put to the left of the first,
--gap bands apart.  The written text is cleared with backspaces after each
case, so every case starts on an empty page with the caret in place.
"""

import argparse
import glob
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import arabic   # noqa: E402

RIGHT_X = 295
BASE_Y = 200
MAX_WIDTH = 270
INK_PER_BAND = 0.51     # the ink's 10th-90th percentile height over the slate's band, the capture page's median
DELETE_KEY = 51         # the ADB delete key: a backspace at the caret

SCRIPT = """// Generated by tools/arabic-ink/audit.py - regenerate, don't edit.
// Known Arabic handwriting written with the pen onto the Notepad and read back.
HostInclude("%(common)s");

name := [2, 0, 45, 34, 14, 37];

auditCases := [
%(cases)s
];

// each case's least wait, in ticks: its points arrive one a tick (the
// paced pen), and the writing is read once the pen has rested
auditWaits := [%(waits)s];

auditParas := func(v, into)
  begin
    if BAnd(v.viewClass, 0xFFFF) = 81 and IsString(v.text) then
      AddArraySlot(into, v);
    foreach child in v:ChildViewFrames() do
      call auditParas with (child, into);
    into;
  end;

auditText := func()
  begin
    local t := "";
    foreach p in call auditParas with (GetRoot(), []) do
      t := t & p.text;
    t;
  end;

auditCodes := func(s)
  begin
    local out := "";
    for i := 0 to StrLen(s) - 1 do
      out := out & (if i > 0 then " " else "") & NumberStr(Ord(s[i]));
    out;
  end;

auditStroke := func(points)
  begin
    PenDown(points[0], points[1]);
    for i := 2 to Length(points) - 2 by 2 do
      PenMove(points[i], points[i + 1]);
    PenUp();
  end;

// the page's text once the case's points have all arrived (least, in
// ticks) and the text has stopped changing (a second the same), or
// whatever it is the seconds after that
auditSettled := func(least, seconds, andThen)
  begin
    local start := Ticks();
    local last := nil;
    local same := 0;
    local poll;
    poll := func() begin
      local t := call auditText with ();
      if StrLen(t) > 0 and last and StrEqual(t, last) then same := same + 1 else same := 0;
      last := t;
      if (same >= 4 and Ticks() - start > least) or Ticks() - start > least + seconds * 60 then
        call andThen with (t)
      else
        AddDelayedCall(poll, nil, 250);
    end;
    AddDelayedCall(poll, nil, 250);
  end;

// every paragraph emptied: the caret put at its end, then backspaces, as
// a user would (a word may have gone into a paragraph of its own)
auditClear := func(andThen)
  begin
    foreach p in call auditParas with (GetRoot(), []) do
      if StrLen(p.text) > 0 then
        begin
          SetKeyView(p, StrLen(p.text));
          for i := 1 to StrLen(p.text) + 1 do
            call typeKey with (%(delete)d);
        end;
    IdleStrokes();
    call waitFor with ("audit: cleared", func() StrLen(call auditText with ()) = 0, andThen, 5);
  end;

auditRun := func(i)
  begin
    if i >= Length(auditCases) then
      begin
        Print("audit: done");
        HostQuit();
      end
    else
      begin
        Print("audit: begin " & NumberStr(i));
        // (the pen paced, a sample a tick, as a real pen's arrive: the
        // strokes take the time writing takes, and carry its times)
        PacePen(true);
        foreach s in auditCases[i] do call auditStroke with (s);
        PacePen(nil);
        call auditSettled with (auditWaits[i], 15, func(t) begin
            Print("audit: read " & NumberStr(i) & " " & call auditCodes with (t));
            call auditClear with (func() call auditRun with (i + 1));
          end);
      end;
  end;

call walkSetup with (name, func() begin
    userConfiguration.hostWordEngine := 9;
    userConfiguration.letterSetSelection := 2;
    ReadCursiveOptions();
    Print("audit: the engine is " & NumberStr(userConfiguration.hostWordEngine));
    call auditRun with (0);
  end);
Print("audit: the script is loaded");
"""


def load_samples(path, limit):
    files = sorted(glob.glob(os.path.join(path, "*.json")))
    out = []
    for f in files:
        with open(f, encoding="utf-8") as h:
            d = json.load(h)
        if d.get("strokes") and d.get("word"):
            out.append((os.path.basename(f)[:-5], d))
    if limit and len(out) > limit:
        step = len(out) / float(limit)
        out = [out[int(i * step)] for i in range(limit)]
    return out


def place(d, band, right):
    """The sample's strokes in whole screen pixels: [[x, y, x, y, ...], ...],
    its right edge at `right`; its width; and the same strokes unrounded."""
    slate = d["slate"]
    xs = [s[i] for s in d["strokes"] for i in range(0, len(s), 4)]
    lo, hi = min(xs), max(xs)
    if slate.get("estimated"):
        # (adab.py's guide lines are guesses: the ink's middle 80% of
        # height is half the band in the capture page's own samples)
        ys = sorted(s[i + 1] for s in d["strokes"] for i in range(0, len(s), 4))
        ink = ys[int(0.9 * (len(ys) - 1))] - ys[int(0.1 * (len(ys) - 1))]
        scale = band * INK_PER_BAND / float(max(ink, 1))
        base = ys[int(0.75 * (len(ys) - 1))]
    else:
        scale = band / float(slate["baseLine"] - slate["topLine"])
        base = slate["baseLine"]
    if hi > lo:
        scale = min(scale, MAX_WIDTH / float(hi - lo))
    strokes = []
    exact = []
    for s in d["strokes"]:
        exact.append([v for i in range(0, len(s), 4)
                      for v in (right - (hi - s[i]) * scale, BASE_Y + (s[i + 1] - base) * scale)])
        pts = []
        for i in range(0, len(s), 4):
            x = int(round(right - (hi - s[i]) * scale))
            y = int(round(BASE_Y + (s[i + 1] - base) * scale))
            if len(pts) >= 2 and pts[-2] == x and pts[-1] == y:
                continue
            pts += [x, y]
        if len(pts) == 2:
            pts += [pts[0] + 1, pts[1] + 1]     # (a dot of one point is a tap to the click recogniser)
        strokes.append(pts)
    return strokes, (hi - lo) * scale, exact


def as_samples(strokes):
    """Screen strokes as the samples' flat [x, y, t, pressure, ...] form."""
    return [[v for i in range(0, len(s), 2) for v in (s[i], s[i + 1], 0, 0.5)] for s in strokes]


def ns_array(strokes):
    return "[" + ", ".join("[" + ", ".join(str(v) for v in s) + "]" for s in strokes) + "]"


def decode_codes(text):
    return "".join(chr(int(c)) for c in text.split()) if text.strip() else ""


def levenshtein(a, b):
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def confusions(a, b):
    """The substitutions, deletions (x -> '') and insertions ('' -> x) that
    take expected a to reading b, by a minimal alignment."""
    n, m = len(a), len(b)
    d = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(n + 1):
        d[i][0] = i
    for j in range(m + 1):
        d[0][j] = j
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            d[i][j] = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] != b[j - 1]))
    out = []
    i, j = n, m
    while i > 0 or j > 0:
        if i > 0 and j > 0 and d[i][j] == d[i - 1][j - 1] + (a[i - 1] != b[j - 1]):
            if a[i - 1] != b[j - 1]:
                out.append((a[i - 1], b[j - 1]))
            i, j = i - 1, j - 1
        elif i > 0 and d[i][j] == d[i - 1][j] + 1:
            out.append((a[i - 1], ""))
            i -= 1
        else:
            out.append(("", b[j - 1]))
            j -= 1
    return out


class Offline:
    def __init__(self, model, lexicon=None, varieties=None):
        import onnxruntime as ort
        import train_net as T
        self.T = T
        with open(os.path.splitext(model)[0] + ".json", encoding="utf-8") as f:
            meta = json.load(f)
        self.alphabet = [c or None for c in meta["alphabet"]]
        self.spaced = " " in self.alphabet          # (the networks since 2026-11-11 read the gaps between words)
        T.STEP = meta.get("step", T.STEP)
        self.sess = ort.InferenceSession(model)
        self.lex = None
        if lexicon:
            import lexdecode
            self.lexdecode = lexdecode
            self.lex = lexdecode.Lexicon(lexicon, varieties)

    def read(self, strokes):
        """The reading the engine would make: by the lexicon when there is
        one (lexdecode.py, which the engine mirrors), else greedy."""
        import numpy as np
        import torch
        feats = self.T.featurize(strokes)
        if feats is None:
            return ""
        logits = self.sess.run(None, {"features": [feats]})[0][0]
        if self.lex is not None:
            lp = logits.astype(np.float64)
            lp = lp - np.logaddexp.reduce(lp, axis=1, keepdims=True)
            return self.lexdecode.read(lp, self.alphabet, self.lex)[0]
        return self.T.greedy(torch.tensor(logits), self.alphabet)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--model", default=os.path.join(REPO, "build", "arabic-ink", "arabic-net-tuned.onnx"))
    ap.add_argument("--anet", help="the .anet newton reads (NEWTON_ARABIC_NET); default: the one it finds")
    ap.add_argument("--lexicon", default=os.path.join(REPO, "build", "arabic-lex", "arabic.lex"),
                    help="the lexicon newton and the offline readings read by (NEWTON_ARABIC_LEXICON); 'none': none")
    ap.add_argument("--varieties", help="the varieties read by (NEWTON_ARABIC_VARIETIES), all by default")
    ap.add_argument("--words", action="append", default=[])
    ap.add_argument("--phrases", action="append", default=[])
    ap.add_argument("--phrase-count", type=int, default=20)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--band", type=float, default=30)
    ap.add_argument("--gap", type=float, default=0.6, help="a phrase's word gap, in bands")
    ap.add_argument("--newton", default=os.path.join(REPO, "build", "host", "host", "newton.exe"))
    ap.add_argument("--out", default=os.path.join(REPO, "build", "arabic-ink", "audit"))
    ap.add_argument("--no-run", action="store_true", help="score the log of an earlier run")
    ap.add_argument("--headless", type=int, default=0, help="the run's limit in seconds (default: 6 a case)")
    a = ap.parse_args()
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass
    os.makedirs(a.out, exist_ok=True)
    lexicon = None if a.lexicon == "none" or not os.path.exists(a.lexicon) else a.lexicon
    print("lexicon: %s" % (lexicon or "none (letter by letter)"))

    # the cases: (kind, id, expected, the original strokes per word, the screen strokes)
    cases = []
    for d in a.words:
        for sid, s in load_samples(d, a.limit):
            screen, _, exact = place(s, a.band, RIGHT_X)
            cases.append(("word", os.path.basename(os.path.normpath(d)) + "/" + sid, arabic.fold(s["word"]),
                          [exact], [screen]))
    for d in a.phrases:
        samples = load_samples(d, 0)
        for k in range(min(a.phrase_count, len(samples) * (len(samples) - 1))):
            (i1, s1), (i2, s2) = samples[k % len(samples)], samples[(k * 7 + 3) % len(samples)]
            if i1 == i2:
                continue
            first, width, exact1 = place(s1, a.band, RIGHT_X)
            room = RIGHT_X - width - a.gap * a.band
            second, width2, exact2 = place(s2, a.band, room)
            if room - width2 < 10:
                continue
            cases.append(("phrase", i1 + "+" + i2, arabic.fold(s1["word"]) + " " + arabic.fold(s2["word"]),
                          [exact1, exact2], [first, second]))

    script = os.path.join(a.out, "audit.ns")
    log = os.path.join(a.out, "audit.log")
    # (HostInclude finds its file beside the script)
    shutil.copyfile(os.path.join(REPO, "src", "host", "demo", "common.ns"), os.path.join(a.out, "common.ns"))
    common = "common.ns"
    with open(script, "w", encoding="utf-8", newline="\n") as f:
        f.write(SCRIPT % {
            "common": common,
            "delete": DELETE_KEY,
            "cases": ",\n".join("  " + ns_array([s for word in c[4] for s in word]) for c in cases),
            # (a tick a point, two a stroke for its pen-down and pen-up, and
            # two and a half seconds for the writing to be read)
            "waits": ", ".join(str(sum(len(s) // 2 + 2 for word in c[4] for s in word) + 150) for c in cases)})
    print("%d cases: %s" % (len(cases), script))

    if not a.no_run:
        env = dict(os.environ, NEWTON_TRACE_ARABIC="1", NEWTON_UNBUFFERED="1")
        if a.anet:
            env["NEWTON_ARABIC_NET"] = a.anet
        env["NEWTON_ARABIC_LEXICON"] = lexicon or "none"
        if a.varieties:
            env["NEWTON_ARABIC_VARIETIES"] = a.varieties
        limit = a.headless or 120 + sum(10 + sum(len(s) // 2 for w in c[4] for s in w) // 60 for c in cases)
        with open(log, "w", encoding="utf-8", errors="replace") as out:
            subprocess.run([a.newton, "--display", "320x480", "--erase", "--store", os.path.join(a.out, "audit.store"),
                            "--script", script, "--headless", str(limit)],
                           stdout=out, stderr=subprocess.STDOUT, env=env, cwd=REPO)

    # the newton run: each case's page text and the engine's readings
    newton = {}
    traces = {}
    current = None
    with open(log, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.search(r'audit: begin (\d+)', line)
            if m:
                current = int(m.group(1))
                traces[current] = []
                continue
            m = re.search(r'audit: read (\d+) ?([\d ]*)', line)
            if m:
                newton[int(m.group(1))] = decode_codes(m.group(2))
                current = None
                continue
            m = re.search(r'\[arabic\] (\d+) strokes, (\d+) points, (\d+) steps: read (\d+) characters \(([0-9a-f ]*)\), confidence (\d+)', line)
            if m and current is not None:
                traces[current].append((int(m.group(1)), int(m.group(2)), "".join(chr(int(c, 16)) for c in m.group(5).split()), int(m.group(6))))
    if "audit: done" not in open(log, encoding="utf-8", errors="replace").read():
        print("the run did not finish: %d of %d cases read (see %s)" % (len(newton), len(cases), log))

    off = Offline(a.model, lexicon, a.varieties)
    rows = []
    stats = {}
    conf = {}
    notes = []
    for n, (kind, cid, expected, original, screen) in enumerate(cases):
        if off.spaced:
            # the whole line read at once, as the engine does now
            r_off = off.read(as_samples([s for w in original for s in w]))
            r_scr = off.read(as_samples([s for w in screen for s in w]))
        else:
            r_off = " ".join(off.read(as_samples(w)) for w in original)
            r_scr = " ".join(off.read(as_samples(w)) for w in screen)
        r_new = newton.get(n)
        page = None if r_new is None else r_new.replace("", "□").strip()
        tr = traces.get(n, [])
        units = len({(t[0], t[1]) for t in tr})
        strokes = sum(len(w) for w in screen)
        conf_ = max((t[3] for t in tr), default=0)
        def norm(t):
            if t is None:
                return None
            if off.lex is not None:     # the lexicon is unvowelled: the marks are not graded
                t = "".join(ch for ch in t if ch not in arabic.MARKS)
            t = " ".join(t.split())
            return t.replace(" ", "") if kind == "word" and not off.spaced else t
        expected, r_off, r_scr, page = norm(expected), norm(r_off), norm(r_scr), norm(page)
        for name, reading in (("offline", r_off), ("screen", r_scr), ("newton", page)):
            st = stats.setdefault((kind, name), [0, 0, 0, 0])
            st[2] += 1
            st[1] += len(expected)
            if reading is None:
                st[0] += len(expected)
                continue
            st[0] += levenshtein(reading, expected)
            st[3] += reading == expected
            if name == "newton":
                for x, y in confusions(expected, reading):
                    conf[(x, y)] = conf.get((x, y), 0) + 1
        if page != r_scr:
            why = []
            if page is None:
                why.append("no reading in time")
            elif "□" in page:
                why.append("ink (confidence %d)" % conf_)
            if tr and units > len(screen):
                why.append("split into %d units" % units)
            if tr and kind == "phrase" and units < 2:
                why.append("the two words read as one")
            if tr and max(t[0] for t in tr) < strokes and units <= len(screen):
                why.append("strokes lost (%d of %d in the largest unit)" % (max(t[0] for t in tr), strokes))
            if not why:
                why.append("the C++ reading differs (units: " + "; ".join("%d strokes %s" % (t[0], t[2]) for t in tr) + ")")
            notes.append("%-6s %-28s want %-14s screen %-14s newton %-14s %s" % (kind, cid, expected, r_scr, page, ", ".join(why)))
        rows.append("\t".join([kind, cid, expected, r_off, r_scr, page if page is not None else "-",
                               str(strokes), str(units), str(conf_)]))

    with open(os.path.join(a.out, "audit.tsv"), "w", encoding="utf-8") as f:
        f.write("kind\tid\texpected\toffline\tscreen\tnewton\tstrokes\tunits\tconfidence\n")
        f.write("\n".join(rows) + "\n")
    lines = ["Arabic engine audit: %d cases, band %g px, model %s" % (len(cases), a.band, os.path.basename(a.model)), ""]
    for kind in ("word", "phrase"):
        for name in ("offline", "screen", "newton"):
            st = stats.get((kind, name))
            if st:
                lines.append("%-6s %-8s letters wrong %5.1f%%   words right %5.1f%%   (%d)" % (
                    kind, name, 100.0 * st[0] / max(1, st[1]), 100.0 * st[3] / max(1, st[2]), st[2]))
    lines += ["", "Where the Newton read differently from the screen points (%d):" % len(notes)] + notes
    top = sorted(conf.items(), key=lambda kv: -kv[1])[:25]
    lines += ["", "Most frequent errors on the Newton (expected -> read, '' none):"]
    lines += ["  %s -> %s  x%d" % (x or "''", y or "''", c) for (x, y), c in top]
    text = "\n".join(lines)
    print(text)
    with open(os.path.join(a.out, "audit.txt"), "w", encoding="utf-8") as f:
        f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
